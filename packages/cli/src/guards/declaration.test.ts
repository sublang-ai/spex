/*
 * Guards package, DR-244 and DR-252: the declaration in TLA+, the
 * file Spex generates from a binding's declaration.
 */

import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { RESERVED, checkNames, declarationModule, typeSet } from "./declaration.js";
import { parseBinding } from "./files.js";
import { GuardError, parseType, vocabulary } from "./types.js";

const BINDING = `format: 1
values:
  user: [ann, bob, cy]
  plan: ["free tier", 'a"b', 'c\\d']
events:
  take:
    params: { who: user }
    effect: { granted: bool, holder: user?, waiting: set of user }
  leave:
    params: { who: user, late: bool }
    effect: { holder: user?, queue: 0..2, debt: -2..3, days: set of 1..3, plans: set of plan? }
  reset: {}
`;

const MODULE = `---- MODULE Declaration ----
\\* Generated by Spex from guards/bindings/lock/binding.yaml. Do not edit.
EXTENDS Integers, FiniteSets, Sequences

\\* The value of a field of a type \`T?\` that holds nothing.
\\* Each .cfg file Spex writes makes it a value equal to nothing else.
CONSTANT Missing

\\* values.user; each value's place in the declared order, from 1;
\\* and the member of a nonempty set of them that comes first in that order.
User == {"ann", "bob", "cy"}
UserRank(v) == CASE v = "ann" -> 1 [] v = "bob" -> 2 [] v = "cy" -> 3
UserFirst(S) == CHOOSE x \\in S : \\A y \\in S : UserRank(x) <= UserRank(y)

\\* values.plan; each value's place in the declared order, from 1;
\\* and the member of a nonempty set of them that comes first in that order.
Plan == {"free tier", "a\\"b", "c\\\\d"}
PlanRank(v) == CASE v = "free tier" -> 1 [] v = "a\\"b" -> 2 [] v = "c\\\\d" -> 3
PlanFirst(S) == CHOOSE x \\in S : \\A y \\in S : PlanRank(x) <= PlanRank(y)

\\* Every event with its params: a record whose field \`event\` names it.
Events ==
  [event : {"take"}, who : User]
  \\cup
  [event : {"leave"}, who : User, late : BOOLEAN]
  \\cup
  [event : {"reset"}]

\\* Every effect the event \`e\` is declared to give.
Effects(e) ==
  CASE e.event = "take" -> [granted : BOOLEAN, holder : (User \\cup {Missing}), waiting : (SUBSET User)]
    [] e.event = "leave" -> [holder : (User \\cup {Missing}), queue : (0..2), debt : ((-2)..3), days : (SUBSET (1..3)), plans : ((SUBSET Plan) \\cup {Missing})]
    [] e.event = "reset" -> {<<>>}
====
`;

describe("declaration: the declaration in TLA+", () => {
  it("generates the same file from the same declaration, every form of type in it", () => {
    const binding = parseBinding(BINDING);
    assert.equal(declarationModule(binding, "lock"), MODULE);
    assert.equal(declarationModule(parseBinding(BINDING), "lock"), MODULE);
  });

  it("writes each type as the TLA+ set of its values", () => {
    const vocab = vocabulary({ user: ["ann"] });
    const set = (type: string): string => typeSet(parseType(type, vocab));
    assert.equal(set("bool"), "BOOLEAN");
    assert.equal(set("user"), "User");
    assert.equal(set("-3..-1"), "((-3)..(-1))");
    assert.equal(set("user?"), "(User \\cup {Missing})");
    assert.equal(set("set of user"), "(SUBSET User)");
  });

  it("refuses a values set whose names in TLA+ are taken", () => {
    const refuse = (values: Record<string, string[]>): string => {
      try {
        checkNames({ vocabulary: vocabulary(values), events: {} });
      } catch (error) {
        assert.ok(error instanceof GuardError);
        return error.message;
      }
      return "";
    };
    assert.equal(refuse({ user: ["a"], plan: ["b"] }), "");
    for (const [set, name] of [["missing", "Missing"], ["events", "Events"], ["effect", "Effect"], ["start", "Start"], ["nat", "Nat"], ["len", "Len"], ["next", "Next"], ["row", "Row"], ["m", "M"], ["any", "Any"], ["sUBSET", "SUBSET"], ["tRUE", "TRUE"]]) {
      assert.ok(RESERVED.has(name));
      assert.equal(refuse({ [set]: ["a"] }), `values: '${set}' cannot name a values set: the declaration in TLA+ would define ${name}, which is taken`);
    }
    assert.equal(
      refuse({ user: ["a"], userFirst: ["b"] }),
      "values: 'userFirst' cannot name a values set: the declaration in TLA+ would define UserFirst, as values user does",
    );
  });
});
