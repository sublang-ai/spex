export const MODEL_MODULE = "SpexModel";

export const MODEL_CFG = `${MISSING_CFG}INIT Init\nNEXT Next\nINVARIANT Declared\nINVARIANT Kept\nCHECK_DEADLOCK FALSE\n`;

export function modelModule(name: string): string {
  return `---- MODULE ${MODEL_MODULE} ----
\\* Generated by Spex. Every state the model reaches, every legal event, against the rule.
EXTENDS Declaration

M == INSTANCE ${name}

VARIABLES state, step

Applies(s, e) == M!When(e) /\\ M!While(s, e)
Forbidden(s, e, f) == Applies(s, e) /\\ ~M!Shall(s, e, f)

\\* One step of the model, with whether the rule applies at it.
Row(s, e) ==
  [ from    |-> s,
    event   |-> e,
    effect  |-> M!Effect(s, e),
    next    |-> M!After(s, e),
    applies |-> Applies(s, e) ]

Init ==
  /\\ state = M!Start
  /\\ step = Missing

\\* A legal event is chosen and its step written down.
Take ==
  /\\ step = Missing
  /\\ \\E e \\in Events : M!Legal(state, e) /\\ step' = Row(state, e)
  /\\ UNCHANGED state

\\* The model moves to the state after it.
Land ==
  /\\ step # Missing
  /\\ state' = step.next
  /\\ step' = Missing

Next == Take \\/ Land

\\* The model's effect is one the event is declared to give.
Declared == step # Missing => step.effect \\in Effects(step.event)

\\* The rule does not forbid the model's effect.
Kept == step # Missing => ~Forbidden(step.from, step.event, step.effect)
====
`;
}

