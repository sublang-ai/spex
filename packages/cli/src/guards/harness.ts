export const COMPARE_MODULE = "SpexCompare";

export const COMPARE_CFG = `${MISSING_CFG}INIT Init\nNEXT Next\nINVARIANT Agree\nCHECK_DEADLOCK FALSE\n`;

export function compareModule(names: readonly string[]): string {
  const first = names[0];
  return `---- MODULE ${COMPARE_MODULE} ----
\\* Generated by Spex. The translations side by side over every sequence of events.
EXTENDS Declaration

${instances(names)}

VARIABLES states, step, diff

${names
  .map(
    (name) =>
      `Applies_${name}(s, e) == T_${name}!When(e) /\\ T_${name}!While(s, e)\nForbidden_${name}(s, e, f) == Applies_${name}(s, e) /\\ ~T_${name}!Shall(s, e, f)`,
  )
  .join("\n")}

\\* Each translation's answer, by its name.
Legal(st, e)        == ${record(names, (name) => `T_${name}!Legal(st.${name}, e)`)}
Effect(st, e)       == ${record(names, (name) => `T_${name}!Effect(st.${name}, e)`)}
Applies(st, e)      == ${record(names, (name) => `Applies_${name}(st.${name}, e)`)}
Forbidden(st, e, f) == ${record(names, (name) => `Forbidden_${name}(st.${name}, e, f)`)}
After(st, e)        == ${record(names, (name) => `T_${name}!After(st.${name}, e)`)}

\\* Whether each translation's effect is one the event is declared to give.
Declared(st, e)     == ${record(names, (name) => `T_${name}!Effect(st.${name}, e) \\in Effects(e)`)}

Same(answers) == \\A x, y \\in DOMAIN answers : answers[x] = answers[y]

\\* The first thing the translations answer differently about the event e, or Missing:
\\* whether it is legal, the effect it gives, whether the rule applies,
\\* then, for every declared effect, whether the rule forbids it.
\\* An effect that is no declared effect is written down before any is compared.
Difference(st, e) ==
  IF ~Same(Legal(st, e)) THEN [on |-> "legal", event |-> e, answers |-> Legal(st, e)]
  ELSE IF ~Legal(st, e).${first} THEN Missing
  ELSE IF \\E x \\in DOMAIN Declared(st, e) : ~Declared(st, e)[x]
    THEN [on |-> "undeclared", event |-> e, answers |-> Effect(st, e), declared |-> Declared(st, e)]
  ELSE IF ~Same(Effect(st, e)) THEN [on |-> "effect", event |-> e, answers |-> Effect(st, e)]
  ELSE IF ~Same(Applies(st, e)) THEN [on |-> "applies", event |-> e, answers |-> Applies(st, e)]
  ELSE
    LET split == {f \\in Effects(e) : ~Same(Forbidden(st, e, f))} IN
    IF split = {} THEN Missing
    ELSE [on |-> "forbidden", event |-> e, model |-> Effect(st, e).${first},
          answers |-> [f \\in split |-> Forbidden(st, e, f)]]

Init ==
  /\\ states = ${record(names, (name) => `T_${name}!Start`)}
  /\\ step = Missing
  /\\ diff = Missing

\\* An event is chosen: a difference about it is written down, or it is taken as the next step.
Take ==
  /\\ step = Missing
  /\\ diff = Missing
  /\\ \\E e \\in Events :
       \\/ /\\ Difference(states, e) # Missing
          /\\ diff' = Difference(states, e)
          /\\ UNCHANGED <<states, step>>
       \\/ /\\ Difference(states, e) = Missing
          /\\ Legal(states, e).${first}
          /\\ step' = [event |-> e, effect |-> Effect(states, e).${first}]
          /\\ UNCHANGED <<states, diff>>

\\* The step chosen is made in every translation.
Land ==
  /\\ step # Missing
  /\\ states' = After(states, step.event)
  /\\ step' = Missing
  /\\ UNCHANGED diff

Next == Take \\/ Land

Agree == diff = Missing
====
`;
}

