/*
 * Guards package, DR-244 and DR-252: the TLA+ files Spex writes
 * around a guard's translations, and their configuration files. Each
 * is fixed text with the translations' names, the cases' steps or the
 * effects the code gave written in. TLC makes every judgement from
 * them; nothing here evaluates TLA+.
 */

import { callToTla, fieldsToTla, tlaString, tlaText } from "./tla.js";
import type { Call, Case, Fields } from "./types.js";

/** What every configuration file starts with: `Missing` as a value
 * of its own, equal to nothing else. */
const MISSING_CFG = "CONSTANT Missing = Missing\n";

/** The configuration of a file TLC only evaluates. */
export const EVALUATE_CFG = MISSING_CFG;

function instances(names: readonly string[]): string {
  return names.map((name) => `T_${name} == INSTANCE ${name}`).join("\n");
}

function record(names: readonly string[], each: (name: string) => string): string {
  return `[${names.map((name) => `${name} |-> ${each(name)}`).join(", ")}]`;
}

// ---------------------------------------------------------------
// 0. Form: one translation alone
// ---------------------------------------------------------------

export const FORM_MODULE = "SpexForm";

export function formModule(name: string): string {
  return `---- MODULE ${FORM_MODULE} ----
\\* Generated by Spex. One translation alone: it parses, and its seven operators take their parameters.
EXTENDS Declaration

T == INSTANCE ${name}

Form(s, e, f) ==
  <<T!Start, T!Legal(s, e), T!Effect(s, e), T!After(s, e), T!When(e), T!While(s, e), T!Shall(s, e, f)>>
====
`;
}

// ---------------------------------------------------------------
// 1. Cases, without the code
// ---------------------------------------------------------------

export const CASES_MODULE = "SpexCases";

function walk(name: string): string {
  return `RECURSIVE Walk_${name}(_, _, _, _, _)
Walk_${name}(steps, forbidden, i, s, applied) ==
  IF i > Len(steps) THEN [pass |-> TRUE, applied |-> applied]
  ELSE
    LET e      == steps[i].event
        stated == steps[i].stated
    IN
    IF e \\notin Events THEN [pass |-> FALSE, step |-> i, why |-> "event not declared"]
    ELSE IF {f \\in Effects(e) : Agrees(f, stated)} = {} THEN [pass |-> FALSE, step |-> i, why |-> "no declared effect is as stated"]
    ELSE IF ~T_${name}!Legal(s, e) THEN [pass |-> FALSE, step |-> i, why |-> "not legal"]
    ELSE
      LET applies == T_${name}!When(e) /\\ T_${name}!While(s, e) IN
      IF forbidden /\\ i = Len(steps)
      THEN
        IF ~applies THEN [pass |-> FALSE, step |-> i, why |-> "rule does not apply"]
        ELSE
          LET open == {f \\in Effects(e) : Agrees(f, stated) /\\ T_${name}!Shall(s, e, f)} IN
          IF open = {} THEN [pass |-> TRUE, applied |-> applied]
          ELSE [pass |-> FALSE, step |-> i, why |-> "not forbidden", allowed |-> open]
      ELSE
        LET f == T_${name}!Effect(s, e) IN
        IF f \\notin Effects(e) THEN [pass |-> FALSE, step |-> i, why |-> "effect not declared", effect |-> f]
        ELSE IF ~Agrees(f, stated) THEN [pass |-> FALSE, step |-> i, why |-> "effect differs", effect |-> f]
        ELSE IF applies /\\ ~T_${name}!Shall(s, e, f) THEN [pass |-> FALSE, step |-> i, why |-> "forbidden", effect |-> f]
        ELSE Walk_${name}(steps, forbidden, i + 1, T_${name}!After(s, e), IF applies THEN applied \\cup {i} ELSE applied)`;
}

/** What one `ASSUME` line of the cases file evaluates: a case under a
 * translation, by the case's number from 1, or whether the rule
 * applied in a permitted case (`case` null). */
export type Assumed = { translation: string; case: number | null };

/**
 * The file that evaluates each case of the guard file under each
 * translation. `assumes` gives, by line number from 1, what each of
 * its `ASSUME` lines evaluates, so a line TLC could not evaluate
 * names its translation and its case.
 */
export function casesModule(names: readonly string[], cases: readonly Case[]): { text: string; assumes: Map<number, Assumed> } {
  const lines: string[] = [
    `---- MODULE ${CASES_MODULE} ----`,
    "\\* Generated by Spex. Each case of the guard file under each translation, without the code.",
    "EXTENDS Declaration, TLC",
    "",
    ...instances(names).split("\n"),
    "",
    "\\* The effect f is as a step states: equal in every field the step states.",
    "Agrees(f, stated) == \\A k \\in DOMAIN stated : k \\in DOMAIN f /\\ f[k] = stated[k]",
    "",
  ];
  cases.forEach((entry, at) => {
    lines.push(`\\* ${entry.kind}: ${entry.label.replace(/[^\x20-\x7e]/g, "?")}`, `Case_${at + 1} == <<`);
    entry.steps.forEach((step, index) => {
      const comma = index === entry.steps.length - 1 ? "" : ",";
      lines.push(`  [event |-> ${tlaText(callToTla(step))}, stated |-> ${tlaText(fieldsToTla(step.effect))}]${comma}`);
    });
    lines.push(">>", "");
  });
  for (const name of names) {
    lines.push(...walk(name).split("\n"), "");
    cases.forEach((entry, at) => {
      const forbidden = entry.kind === "forbidden" ? "TRUE" : "FALSE";
      lines.push(`Result_${name}_${at + 1} == Walk_${name}(Case_${at + 1}, ${forbidden}, 1, T_${name}!Start, {})`);
    });
    const permitted = cases.flatMap((entry, at) => (entry.kind === "permitted" ? [at + 1] : []));
    const applied =
      permitted.length === 0
        ? "FALSE"
        : permitted.map((k) => `(Result_${name}_${k}.pass /\\ Result_${name}_${k}.applied # {})`).join(" \\/ ");
    lines.push(`Applied_${name} == ${applied}`, "");
  }
  const assumes = new Map<number, Assumed>();
  for (const name of names) {
    cases.forEach((_, at) => {
      lines.push(`ASSUME PrintT(<<"case", ${tlaString(name)}, ${at + 1}, Result_${name}_${at + 1}>>)`);
      assumes.set(lines.length, { translation: name, case: at + 1 });
    });
    lines.push(`ASSUME PrintT(<<"applied", ${tlaString(name)}, Applied_${name}>>)`);
    assumes.set(lines.length, { translation: name, case: null });
  }
  lines.push("====", "");
  return { text: lines.join("\n"), assumes };
}

