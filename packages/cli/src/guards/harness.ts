// 4. Judging an effect the code gave
// ---------------------------------------------------------------

export const JUDGE_MODULE = "SpexJudge";

/** One effect the code gave that is not the model's: the events
 * caused before it from a fresh start, its own event, and the effect. */
export type Observation = { before: readonly Call[]; call: Call; effect: Fields };

export function judgeModule(name: string, observed: readonly Observation[]): string {
  const lines = observed.map((one, at) => {
    const before = `<<${one.before.map((call) => tlaText(callToTla(call))).join(", ")}>>`;
    return `ASSUME PrintT(<<"judge", ${at + 1}, Judge(${before}, ${tlaText(callToTla(one.call))}, ${tlaText(fieldsToTla(one.effect))})>>)`;
  });
  return `---- MODULE ${JUDGE_MODULE} ----
\\* Generated by Spex. What the rule says of effects the code gave.
EXTENDS Declaration, TLC

M == INSTANCE ${name}

\\* The model's state after the first n of a sequence of events.
RECURSIVE Reached(_, _)
Reached(events, n) == IF n = 0 THEN M!Start ELSE M!After(Reached(events, n - 1), events[n])

Forbidden(s, e, f) == M!When(e) /\\ M!While(s, e) /\\ ~M!Shall(s, e, f)

\\* Whether the rule forbids the event e to give the effect f after a sequence of events.
Judge(events, e, f) == Forbidden(Reached(events, Len(events)), e, f)

${lines.join("\n")}
====
`;
}
