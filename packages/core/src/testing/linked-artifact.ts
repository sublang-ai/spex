// A compiled fixture whose artifact imports the engine as `slc`'s link
// emits it (playbook-library-47, -108): Playbook's own `review` — the
// source it was compiled from, its machine and the runtime `slc`'s link
// materialized over it, as the engine the repository installs ships
// them — with the registry entry `slc` emits beside the artifact
// directory and the `capture.json` a stub `slc` reads, so a compile
// through that stub packages what a real compile packages. Not
// re-exported from `./index.ts`: the resolution recorder registers
// Node's module hooks, a test's business alone.

import { mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { ARTIFACT_SCHEMAS } from "../config.js";

/** The fixture's playbook id: Playbook's own. */
export const LINKED_ID = "review";

/** The engine module the app itself runs, as Node's ESM loader names it. */
export const APP_ENGINE_URL = import.meta.resolve("@sublang/playbook/xstate-runtime");

/** The machine library the app's engine runs, as the loader names it. */
export const APP_XSTATE_URL = import.meta.resolve("xstate");

/** The registry entry `slc` emits beside the artifact directory, in the
 * shape of its emission for a linked artifact. */
function entrySource(id: string, roles: readonly string[]): string {
  return `// Generated by slc (DR-014): the registry entry exposing the compiled
// playbook to \`playbook run\`.

import createPlaybookRuntime, { validateOptions as linkedValidateOptions } from './${id}.playbook/${id}.playbook.ts';

type FactoryInput = NonNullable<Parameters<typeof createPlaybookRuntime>[0]>;
type RuntimeOptions = FactoryInput['configuredOptions'];
type HostCapabilities = FactoryInput['hostCapabilities'];

const REQUIRED_ROLE_IDS: readonly string[] = ${JSON.stringify(roles)};

const validateOptions: (value: unknown) => RuntimeOptions = linkedValidateOptions;

const entry = {
  id: '${id}',
  command: '${id}',
  intent: 'Review a change',
  artifactSchema: ${ARTIFACT_SCHEMAS[ARTIFACT_SCHEMAS.length - 1]},
  runtimeProfile: Object.freeze({
    kind: 'shared-factory',
    compat: createPlaybookRuntime.compat,
  }),
  concurrentRoleSets: [] as readonly (readonly string[])[],
  requiredRoleIds: [...REQUIRED_ROLE_IDS],
  validateOptions,
  createRuntime(options: { captainOptions?: unknown },
    hostCapabilities: HostCapabilities) {
    const validated = validateOptions(options.captainOptions);
    return createPlaybookRuntime({
      configuredOptions: validated,
      hostCapabilities,
    });
  },
};

export default entry;
`;
}

/**
 * Write the fixture into `dir` — `review.md`, `review.playbook/` with
 * the machine, the linked runtime and the gears, `review.ts` and
 * `capture.json` — and return `dir`, for a stub `slc` given it as its
 * compiled fixture.
 */
export function writeLinkedFixture(dir: string): string {
  const root = dirname(dirname(fileURLToPath(APP_ENGINE_URL)));
  const reference = join(root, "reference", "sdlc");
  const id = LINKED_ID;
  mkdirSync(join(dir, `${id}.playbook`), { recursive: true });
  writeFileSync(join(dir, `${id}.md`), readFileSync(join(reference, `${id}.md`)));
  for (const stage of ["fsm.ts", "gears.md"]) {
    writeFileSync(join(dir, `${id}.playbook`, `${id}.${stage}`), readFileSync(join(reference, `${id}.playbook`, `${id}.${stage}`)));
  }
  // slc's link names the machine by its `.ts` file, as it emits it.
  const linked = readFileSync(join(reference, `${id}.playbook`, `${id}.playbook.ts`), "utf8")
    .replaceAll(`"./${id}.fsm.js"`, `"./${id}.fsm.ts"`);
  writeFileSync(join(dir, `${id}.playbook`, `${id}.playbook.ts`), linked);
  writeFileSync(join(dir, `${id}.ts`), entrySource(id, ["coder", "reviewer"]));
  writeFileSync(join(dir, "capture.json"), JSON.stringify({ playbookId: id }));
  return dir;
}

/** One resolution Node's loader made: what was asked, from where, and
 * the module it named. */
export interface Resolution {
  specifier: string;
  parentURL: string | undefined;
  url: string;
}

/** Run `work`, recording every resolution Node's ESM loader makes
 * meanwhile through its module hooks. */
export async function recordingResolutions<T>(work: () => Promise<T>): Promise<{ value: T; resolutions: Resolution[] }> {
  const resolutions: Resolution[] = [];
  const hooks = registerHooks({
    resolve(specifier, context, nextResolve) {
      const result = nextResolve(specifier, context);
      resolutions.push({ specifier, parentURL: context.parentURL, url: result.url });
      return result;
    },
  });
  try {
    return { value: await work(), resolutions };
  } finally {
    hooks.deregister();
  }
}

/** The modules a file's own imports resolved to, by specifier: the
 * loader names a module by its real path, so the file is too. */
export function importsOf(resolutions: readonly Resolution[], file: string): Map<string, string> {
  const real = realpathSync(file);
  const out = new Map<string, string>();
  for (const resolution of resolutions) {
    if (!resolution.parentURL?.startsWith("file:")) continue;
    if (fileURLToPath(new URL(resolution.parentURL.split("?")[0]!)) !== real) continue;
    out.set(resolution.specifier, resolution.url);
  }
  return out;
}
